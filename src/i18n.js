// Five-language UI localisation for the overseas PC showcase.
// - t(key, vars): fixed UI strings from MESSAGES below.
// - tx(str): free-form demo strings (product names, categories, units, tags,
//   blurbs, spec keys/values) translated via STRINGS, keyed by the English
//   source text; unknown strings (e.g. live API data) pass through unchanged.
// - The visitor's choice persists in localStorage; the admin default comes
//   from pc-config.json (siteConfig.defaultLanguage).
import { ref } from 'vue'
import { siteConfig } from './siteConfig.js'

export const LANGS = [
  { code: 'en', label: 'English' },
  { code: 'zh', label: '中文' },
  { code: 'es', label: 'Español' },
  { code: 'fr', label: 'Français' },
  { code: 'pt', label: 'Português' }
]

export const locale = ref('en')
try {
  const saved = localStorage.getItem('taojie-lang')
  if (saved && LANGS.some((l) => l.code === saved)) locale.value = saved
} catch { /* storage unavailable */ }

export function setLocale(code) {
  if (!LANGS.some((l) => l.code === code)) return
  locale.value = code
  try { localStorage.setItem('taojie-lang', code) } catch { /* ignore */ }
}

// Called once from main.js after pc-config.json has loaded: the admin's
// default language applies only when the visitor has not chosen one.
export function initLocaleFromConfig() {
  try { if (localStorage.getItem('taojie-lang')) return } catch { /* ignore */ }
  const d = siteConfig.defaultLanguage
  if (d && LANGS.some((l) => l.code === d)) locale.value = d
}

export function t(key, vars) {
  let s = (MESSAGES[locale.value] && MESSAGES[locale.value][key]) ?? MESSAGES.en[key] ?? key
  if (vars && typeof s === 'string') {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}

export function tx(str) {
  if (typeof str !== 'string' || !str) return str
  const dict = STRINGS[locale.value]
  return (dict && dict[str]) || str
}

export function themeText(key) {
  const per = THEME_TEXT[key] || THEME_TEXT.h
  return per[locale.value] || per.en
}

